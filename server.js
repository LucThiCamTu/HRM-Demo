async function start() {
  await initializeDatabase();

  // Đặt lịch kiểm tra tự động chạy ngầm mỗi 1 giờ
  setInterval(() => {
    autoGenerateDailyAttendance();
  }, 60 * 60 * 1000);

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`HRM đang chạy tại http://localhost:${PORT}`);
  });
}

start();
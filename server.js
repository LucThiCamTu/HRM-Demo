const express = require("express");
const { Pool } = require("pg");
const path = require("path");

const app = express();
const PORT = Number(process.env.PORT || 3000);

app.use(express.json());
app.use(express.urlencoded({ extended: true }));

const pool = new Pool({
  host: process.env.DB_HOST || process.env.POSTGRES_HOST || "localhost",
  port: Number(process.env.DB_PORT || 5432),
  database: process.env.DB_NAME || process.env.POSTGRES_DB || "hrm_db",
  user: process.env.DB_USER || process.env.POSTGRES_USER || "hrm_user",
  password: process.env.DB_PASSWORD || process.env.POSTGRES_PASSWORD || "change_me",
});

app.use(express.static(path.join(__dirname, "public")));

// Hàm tự động quét và tạo bản ghi chấm công cho ngày hiện tại
async function autoGenerateDailyAttendance() {
  try {
    await pool.query(`
      INSERT INTO hrm_attendance (employee_id, attendance_date, status)
      SELECT id, CURRENT_DATE, 
             CASE 
               WHEN status = 'Nghỉ phép' THEN 'Nghỉ phép'
               ELSE 'Có mặt'
             END
      FROM hrm_employees
      WHERE status != 'Đã nghỉ việc'
      ON CONFLICT (employee_id, attendance_date) DO NOTHING;
    `);
    console.log(`[TỰ ĐỘNG CHẤM CÔNG] Đã cập nhật chấm công ngày ${new Date().toISOString().slice(0,10)}`);
  } catch (err) {
    console.error("Lỗi tự động chấm công:", err.message);
  }
}

async function initializeDatabase() {
  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS hrm_departments (
        id SERIAL PRIMARY KEY,
        department_code VARCHAR(30) UNIQUE NOT NULL,
        name VARCHAR(150) NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS hrm_employees (
        id SERIAL PRIMARY KEY,
        employee_code VARCHAR(30) UNIQUE NOT NULL,
        full_name VARCHAR(150) NOT NULL,
        email VARCHAR(150),
        phone VARCHAR(30),
        gender VARCHAR(20),
        position VARCHAR(100),
        department_id INTEGER REFERENCES hrm_departments(id) ON DELETE SET NULL,
        status VARCHAR(30) NOT NULL DEFAULT 'Đang làm việc',
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS hrm_attendance (
        id SERIAL PRIMARY KEY,
        employee_id INTEGER NOT NULL REFERENCES hrm_employees(id) ON DELETE CASCADE,
        attendance_date DATE NOT NULL,
        status VARCHAR(30) NOT NULL DEFAULT 'Có mặt',
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(employee_id, attendance_date)
      );
    `);

    await pool.query(`
      INSERT INTO hrm_departments (department_code, name)
      VALUES ('PB01', 'Công nghệ thông tin'), ('PB02', 'Kế toán'), ('PB03', 'Nhân sự')
      ON CONFLICT (department_code) DO NOTHING;
    `);

    await pool.query(`
      INSERT INTO hrm_employees (employee_code, full_name, email, phone, gender, position, department_id)
      SELECT v.code, v.full_name, v.email, v.phone, v.gender, v.position, d.id
      FROM (
        VALUES
          ('NV001', 'Nguyễn Văn An', 'an@example.com', '0912345678', 'Nam', 'Lập trình viên', 'PB01'),
          ('NV002', 'Trần Thị Bình', 'binh@example.com', '0987654321', 'Nữ', 'Kế toán viên', 'PB02'),
          ('NV003', 'Lê Minh Châu', 'chau@example.com', '0905123456', 'Nữ', 'Chuyên viên nhân sự', 'PB03')
      ) AS v(code, full_name, email, phone, gender, position, dept_code)
      JOIN hrm_departments d ON d.department_code = v.dept_code
      ON CONFLICT (employee_code) DO NOTHING;
    `);

    await autoGenerateDailyAttendance();
    console.log("Khởi tạo CSDL thành công.");
  } catch (err) {
    console.error("Lỗi khởi tạo DB:", err.message);
  }
}

function employeeOutput(row) {
  return {
    ...row,
    employeeId: row.id,
    maNV: row.employee_code,
    fullName: row.full_name,
    name: row.full_name,
    email: row.email,
    phone: row.phone,
    gender: row.gender,
    position: row.position,
    departmentId: row.department_id,
    departmentName: row.department_name,
    status: row.status,
  };
}

const employeeSelect = `
  SELECT e.id, e.employee_code, e.full_name, e.email,
         e.phone, e.gender, e.position, e.department_id,
         e.status, e.created_at, d.name AS department_name
  FROM hrm_employees e
  LEFT JOIN hrm_departments d ON d.id = e.department_id
`;

// API Lấy danh sách nhân viên
app.get("/api/employees", async (req, res) => {
  try {
    const keyword = String(req.query.q || req.query.search || "").trim();
    const result = await pool.query(
      employeeSelect + `
        WHERE $1 = ''
          OR e.employee_code ILIKE '%' || $1 || '%'
          OR e.full_name ILIKE '%' || $1 || '%'
          OR COALESCE(e.email, '') ILIKE '%' || $1 || '%'
          OR COALESCE(e.position, '') ILIKE '%' || $1 || '%'
        ORDER BY e.id DESC
      `,
      [keyword]
    );
    res.json(result.rows.map(employeeOutput));
  } catch (error) {
    res.status(500).json({ message: "Không tải được danh sách nhân viên." });
  }
});

// API Thêm mới nhân viên
app.post("/api/employees", async (req, res) => {
  try {
    const { employee_code, full_name, email, phone, gender, position, department_id, status } = req.body;
    const result = await pool.query(`
      INSERT INTO hrm_employees (employee_code, full_name, email, phone, gender, position, department_id, status)
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
      RETURNING *
    `, [employee_code, full_name, email, phone, gender || 'Nam', position, department_id || null, status || 'Đang làm việc']);
    
    if (status !== 'Đã nghỉ việc') {
      await autoGenerateDailyAttendance();
    }

    res.json({ success: true, data: result.rows[0] });
  } catch (error) {
    res.status(500).json({ message: "Mã nhân viên đã tồn tại hoặc dữ liệu không hợp lệ." });
  }
});

// API Cập nhật thông tin nhân viên
app.put("/api/employees/:id", async (req, res) => {
  try {
    const { id } = req.params;
    const { full_name, email, phone, position, department_id, status } = req.body;
    await pool.query(`
      UPDATE hrm_employees
      SET full_name = $1, email = $2, phone = $3, position = $4, department_id = $5, status = $6
      WHERE id = $7
    `, [full_name, email, phone, position, department_id || null, status, id]);

    await autoGenerateDailyAttendance();
    res.json({ success: true });
  } catch (error) {
    res.status(500).json({ message: "Lỗi khi cập nhật nhân viên." });
  }
});


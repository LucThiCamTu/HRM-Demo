// API Danh sách phòng ban
app.get("/api/departments", async (req, res) => {
  try {
    const result = await pool.query(`
      SELECT d.id, d.department_code, d.name, COUNT(e.id)::int AS employee_count
      FROM hrm_departments d
      LEFT JOIN hrm_employees e ON e.department_id = d.id
      GROUP BY d.id ORDER BY d.id
    `);
    res.json(result.rows.map(d => ({ ...d, departmentId: d.id, code: d.department_code, departmentName: d.name, employeeCount: d.employee_count })));
  } catch (error) {
    res.status(500).json({ message: "Không tải được phòng ban." });
  }
});

// API Chấm công (Loại bỏ nhân viên đã nghỉ việc & đồng bộ nghỉ phép)
app.get("/api/attendance", async (req, res) => {
  try {
    const date = String(req.query.date || "").slice(0, 10);
    const values = date ? [date] : [];
    const whereDate = date ? "WHERE a.attendance_date = $1" : "";

    const result = await pool.query(`
      SELECT a.id, a.employee_id, TO_CHAR(a.attendance_date, 'YYYY-MM-DD') AS attendance_date, 
             CASE 
               WHEN e.status = 'Nghỉ phép' THEN 'Nghỉ phép'
               ELSE a.status
             END AS status,
             e.employee_code, e.full_name, e.status AS emp_status
      FROM hrm_attendance a
      JOIN hrm_employees e ON e.id = a.employee_id
      ${whereDate}
      ${whereDate ? "AND" : "WHERE"} e.status != 'Đã nghỉ việc'
      ORDER BY a.attendance_date DESC, a.id DESC
    `, values);

    res.json(result.rows.map(a => ({
      ...a,
      employeeId: a.employee_id,
      maNV: a.employee_code,
      employeeName: a.full_name,
      date: a.attendance_date,
      attendanceDate: a.attendance_date
    })));
  } catch (error) {
    res.status(500).json({ message: "Không tải được dữ liệu chấm công." });
  }
});

// API Cập nhật/Điểm danh chấm công
app.post("/api/attendance", async (req, res) => {
  try {
    const { employee_id, attendance_date, status } = req.body;
    const date = attendance_date || new Date().toISOString().slice(0, 10);

    const result = await pool.query(`
      INSERT INTO hrm_attendance (employee_id, attendance_date, status)
      VALUES ($1, $2, $3)
      ON CONFLICT (employee_id, attendance_date) 
      DO UPDATE SET status = EXCLUDED.status
      RETURNING *;
    `, [employee_id, date, status || 'Có mặt']);

    res.json({ success: true, data: result.rows[0] });
  } catch (error) {
    res.status(500).json({ message: "Không thể cập nhật chấm công." });
  }
});

